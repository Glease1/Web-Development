  <h2>1. Who We Are</h2>
  <p>Meridian Horizons Ltd ("<strong>Meridian</strong>", "<strong>we</strong>", "<strong>us</strong>") is the data controller for personal information collected through this website and in connection with our travel services. We are registered with the Information Commissioner's Office (ICO) under reference ZA123456.</p>
  <p>If you have questions about this policy or wish to exercise your rights, contact our Data Protection Officer at <a href="mailto:privacy@meridianhorizons.co.uk">privacy@meridianhorizons.co.uk</a> or write to 12 Queen Square, Bath, BA1 2HN.</p>

  <h2>2. Information We Collect</h2>
  <p>We collect and process the following categories of personal information:</p>
  <ul>
    <li><strong>Identity data:</strong> name, title, date of birth (where required for bookings)</li>
    <li><strong>Contact data:</strong> email address, telephone number, postal address</li>
    <li><strong>Booking data:</strong> passport details, travel preferences, dietary requirements, medical information relevant to your trip</li>
    <li><strong>Financial data:</strong> payment card details (processed through our secure payment gateway; we do not store full card numbers)</li>
    <li><strong>Technical data:</strong> IP address, browser type and version, time zone, cookie data, pages visited</li>
    <li><strong>Marketing preferences:</strong> your preferences for receiving marketing from us</li>
  </ul>
  <p>We do not collect any special categories of sensitive data (such as race, ethnicity, or political opinions) unless specifically necessary to provide your travel arrangements (e.g. dietary requirements for religious reasons).</p>

  <h2>3. How We Use Your Information</h2>
  <p>We use your personal data for the following purposes and on the following legal bases:</p>
  <ul>
    <li><strong>To fulfil your booking</strong> (contractual necessity): process payments, communicate itinerary details, liaise with hotels and airlines, provide in-destination support.</li>
    <li><strong>To communicate with you about your enquiry</strong> (legitimate interest): respond to contact form submissions, quote requests, and general questions.</li>
    <li><strong>To improve our website and services</strong> (legitimate interest): analyse how visitors use our site, identify and fix issues, develop new features.</li>
    <li><strong>To send you marketing communications</strong> (consent): if you have opted in, we may send you inspiration, destination guides, and special offers. You can withdraw consent at any time.</li>
    <li><strong>To comply with legal obligations</strong>: retain financial records, cooperate with regulatory enquiries.</li>
  </ul>

  <h2>4. Who We Share Your Data With</h2>
  <p>We share personal data only where necessary:</p>
  <ul>
    <li><strong>Travel suppliers</strong> (airlines, hotels, transfer companies, tour operators): to fulfil your booking. These suppliers process data as independent controllers under their own privacy policies.</li>
    <li><strong>Payment processors</strong>: to process card transactions securely.</li>
    <li><strong>Email service providers</strong>: to send transactional and marketing emails.</li>
    <li><strong>Analytics providers</strong>: anonymised data used to understand website usage.</li>
    <li><strong>Legal and regulatory authorities</strong>: where required by law.</li>
  </ul>
  <p>We never sell your personal data to third parties.</p>

  <h2>5. International Transfers</h2>
  <p>Some of our travel suppliers are based outside the UK and European Economic Area (EEA). Where we transfer data to countries that do not provide an equivalent level of data protection, we ensure appropriate safeguards are in place (such as Standard Contractual Clauses approved by the ICO).</p>

  <h2>6. Data Retention</h2>
  <p>We retain personal data only for as long as necessary:</p>
  <ul>
    <li>Booking and financial records: 7 years (legal requirement)</li>
    <li>Account information: until account deletion or 3 years of inactivity</li>
    <li>Marketing consent records: until consent is withdrawn</li>
    <li>Enquiry data (non-booking): 2 years</li>
    <li>Website analytics: 26 months (aggregated; no individual identification)</li>
  </ul>

  <h2>7. Your Rights</h2>
  <p>Under UK GDPR, you have the right to:</p>
  <ul>
    <li><strong>Access</strong> the personal data we hold about you</li>
    <li><strong>Correct</strong> inaccurate or incomplete data</li>
    <li><strong>Delete</strong> your data (subject to legal retention obligations)</li>
    <li><strong>Restrict</strong> or <strong>object</strong> to certain processing</li>
    <li><strong>Portability</strong>: receive your data in a structured, machine-readable format</li>
    <li><strong>Withdraw consent</strong> at any time where processing is based on consent</li>
  </ul>
  <p>To exercise any of these rights, email <a href="mailto:privacy@meridianhorizons.co.uk">privacy@meridianhorizons.co.uk</a>. We will respond within 30 days. You also have the right to lodge a complaint with the ICO at <a href="https://ico.org.uk" target="_blank" rel="noopener">ico.org.uk</a>.</p>

  <h2>8. Cookies</h2>
  <p>We use cookies and similar technologies to operate the website and understand how it is used. For full details, see our <a href="/?page=cookies">Cookie Policy</a>.</p>

  <h2>9. Security</h2>
  <p>We implement appropriate technical and organisational measures to protect your personal data against accidental or unlawful destruction, loss, alteration, or unauthorised disclosure. These include encrypted connections (HTTPS), access controls, regular security reviews, and staff training.</p>
  <p>Despite these measures, no internet transmission is completely secure. If you have reason to believe your interaction with us is no longer secure, please contact us immediately.</p>

  <h2>10. Changes to This Policy</h2>
  <p>We may update this policy periodically. The "last updated" date at the top of this page will reflect any changes. Where changes are significant, we will notify you by email.</p>

